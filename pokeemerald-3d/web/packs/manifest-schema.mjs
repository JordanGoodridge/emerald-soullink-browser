// Declarative game-pack manifest validation.
//
// Pure module: no DOM, storage, network or WASM dependencies. The loader uses
// this before importing a pack; the CLI validator uses the same rules.
//
// The manifest is the only place the shell learns what a game is and what it
// may enable. Keep it data-only: no scripts, ROM bytes or credentials.

export const MANIFEST_SCHEMA_VERSION = 1;
export const PACK_ID_RE = /^[a-z0-9-]{1,32}$/;
export const FORMAT_ID_RE = /^[a-z0-9-]{1,48}$/;
export const CONTENT_VERSION_RE = /^[A-Za-z0-9_.:-]{1,64}$/;
export const VERSION_RE = /^[A-Za-z0-9_.:+-]{1,64}$/;
export const RESOURCE_GROUPS = Object.freeze(['boot', 'presence', 'optional']);
export const RESOURCE_KINDS = Object.freeze([
  'runtime', 'image', 'data', 'avatar', 'patch', 'base',
]);
export const RENDERING_MODES = Object.freeze(['hd2d', 'classic']);
export const SCENE_FORMATS = Object.freeze(['emerald-scene-v1', 'gba-classic-v1']);
export const PRESENCE_LEVELS = Object.freeze(['none', 'readonly']);
export const RULES_LEVELS = Object.freeze(['none', 'observe', 'enforce']);
export const LINK_LEVELS = Object.freeze(['none']);
export const INTERIOR_SUPPORT_LEVELS = Object.freeze(['inherited', 'unsupported', 'verified']);

const REQUIRED_SECTIONS = ['game', 'build', 'runtime', 'rendering', 'resources', 'saves', 'capabilities'];

function isObject(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function isNonEmptyString(value) {
  return typeof value === 'string' && value.length > 0;
}

function isStringArray(value) {
  return Array.isArray(value) && value.every(isNonEmptyString);
}

function isPositiveInteger(value) {
  return Number.isSafeInteger(value) && value > 0;
}

function isNonNegativeInteger(value) {
  return Number.isSafeInteger(value) && value >= 0;
}

// Adapter and codec entries are pack-relative by contract. A leading slash or
// a parent segment would let a pack import outside its own directory.
export function isPackRelativePath(value) {
  if (!isNonEmptyString(value)) return false;
  if (value.startsWith('/') || value.startsWith('\\')) return false;
  if (value.includes('\\')) return false;
  const segments = value.split('/');
  return segments.every((segment) => segment !== '' && segment !== '.' && segment !== '..');
}

export function isResourceUrl(value) {
  if (!isNonEmptyString(value)) return false;
  if (isPackRelativePath(value)) return true;
  // Root-relative resources are allowed when the server maps them explicitly
  // (for example /graphics/**). Protocol-relative URLs are not.
  if (value.startsWith('/') && !value.startsWith('//')) return true;
  try {
    const parsed = new URL(value);
    return parsed.protocol === 'https:' || parsed.protocol === 'http:';
  } catch {
    return false;
  }
}

function addError(errors, path, message) {
  errors.push({ path, message });
}

function validateResource(resource, path, errors, { requireDigests }) {
  if (!isObject(resource)) {
    addError(errors, path, 'must be an object');
    return;
  }
  for (const key of ['id', 'kind', 'group']) {
    if (!isNonEmptyString(resource[key])) addError(errors, `${path}.${key}`, 'must be a non-empty string');
  }
  if (!RESOURCE_KINDS.includes(resource.kind)) {
    addError(errors, `${path}.kind`, `must be one of ${RESOURCE_KINDS.join(', ')}`);
  }
  if (!RESOURCE_GROUPS.includes(resource.group)) {
    addError(errors, `${path}.group`, `must be one of ${RESOURCE_GROUPS.join(', ')}`);
  }
  if (typeof resource.embedded !== 'boolean') {
    addError(errors, `${path}.embedded`, 'must be a boolean');
  }
  if (resource.embedded === false) {
    if (!isResourceUrl(resource.url)) addError(errors, `${path}.url`, 'must be a pack-relative or same-origin URL');
    if (requireDigests && !isNonEmptyString(resource.sha256)) {
      addError(errors, `${path}.sha256`, 'is required for external resources');
    }
    if (requireDigests && resource.sha256 === 'pending') {
      addError(errors, `${path}.sha256`, 'must be generated by the packager');
    }
    if (resource.sha256 !== undefined && resource.sha256 !== 'pending' && !/^[a-f0-9]{64}$/i.test(resource.sha256)) {
      addError(errors, `${path}.sha256`, 'must be 64 hex characters or "pending"');
    }
  }
  if (resource.bytes !== undefined && !isPositiveInteger(resource.bytes)) {
    addError(errors, `${path}.bytes`, 'must be a positive integer');
  }
}

function validateRuntime(runtime, errors, { requireDigests }) {
  if (!isObject(runtime)) {
    addError(errors, 'runtime', 'must be an object');
    return;
  }
  if (runtime.kind !== 'source-wasm') addError(errors, 'runtime.kind', 'must be "source-wasm"');
  if (!isPackRelativePath(runtime.adapter)) addError(errors, 'runtime.adapter', 'must be a pack-relative module path');
  if (!isPositiveInteger(runtime.abiVersion)) addError(errors, 'runtime.abiVersion', 'must be a positive integer');
  if (!isStringArray(runtime.entry) || runtime.entry.length === 0) {
    addError(errors, 'runtime.entry', 'must be a non-empty string array');
  }
  if (!isStringArray(runtime.requiredExports)) {
    addError(errors, 'runtime.requiredExports', 'must be a string array');
  }
  if (runtime.optionalExports !== undefined && !isStringArray(runtime.optionalExports)) {
    addError(errors, 'runtime.optionalExports', 'must be a string array');
  }
  if (runtime.initialMemoryBytes !== undefined && !isPositiveInteger(runtime.initialMemoryBytes)) {
    addError(errors, 'runtime.initialMemoryBytes', 'must be a positive integer');
  }
  if (!isObject(runtime.module)) {
    addError(errors, 'runtime.module', 'must be a resource object');
    return;
  }
  validateResource(runtime.module, 'runtime.module', errors, { requireDigests });
  if (runtime.module.kind !== 'runtime') addError(errors, 'runtime.module.kind', 'must be "runtime"');
}

function validateRendering(rendering, errors) {
  if (!isObject(rendering)) {
    addError(errors, 'rendering', 'must be an object');
    return;
  }
  if (!Array.isArray(rendering.modes) || rendering.modes.length === 0) {
    addError(errors, 'rendering.modes', 'must be a non-empty array');
  } else {
    for (const mode of rendering.modes) {
      if (!RENDERING_MODES.includes(mode)) addError(errors, 'rendering.modes', `unknown mode ${mode}`);
    }
    if (new Set(rendering.modes).size !== rendering.modes.length) {
      addError(errors, 'rendering.modes', 'must not contain duplicates');
    }
    if (!rendering.modes.includes(rendering.defaultMode)) {
      addError(errors, 'rendering.defaultMode', 'must be present in rendering.modes');
    }
  }
  if (!SCENE_FORMATS.includes(rendering.sceneFormat)) {
    addError(errors, 'rendering.sceneFormat', `must be one of ${SCENE_FORMATS.join(', ')}`);
  }
  if (!isPositiveInteger(rendering.width) || !isPositiveInteger(rendering.height)) {
    addError(errors, 'rendering.width/height', 'must be positive integers');
  }
  if (!isPackRelativePath(rendering.adapter)) addError(errors, 'rendering.adapter', 'must be a pack-relative module path');
}

function validateSaves(saves, errors) {
  if (!isObject(saves)) {
    addError(errors, 'saves', 'must be an object');
    return;
  }
  if (!FORMAT_ID_RE.test(saves.formatId || '')) addError(errors, 'saves.formatId', 'must match [a-z0-9-]{1,48}');
  if (!isPositiveInteger(saves.formatVersion)) addError(errors, 'saves.formatVersion', 'must be a positive integer');
  if (!isPositiveInteger(saves.bytes)) addError(errors, 'saves.bytes', 'must be a positive integer');
  if (!isPackRelativePath(saves.codec)) addError(errors, 'saves.codec', 'must be a pack-relative module path');
  if (saves.legacyStorageKeys !== undefined && !isStringArray(saves.legacyStorageKeys)) {
    addError(errors, 'saves.legacyStorageKeys', 'must be a string array');
  }
  if (saves.profilePattern !== undefined && typeof saves.profilePattern !== 'string') {
    addError(errors, 'saves.profilePattern', 'must be a string');
  }
  if (saves.exportName !== undefined && !isNonEmptyString(saves.exportName)) {
    addError(errors, 'saves.exportName', 'must be a non-empty filename');
  }
}

function validateMultiplayer(multiplayer, errors) {
  if (!isObject(multiplayer)) {
    addError(errors, 'multiplayer', 'must be an object when presence is enabled');
    return;
  }
  if (!isPositiveInteger(multiplayer.protocol)) addError(errors, 'multiplayer.protocol', 'must be a positive integer');
  if (!CONTENT_VERSION_RE.test(multiplayer.contentVersion || '')) {
    addError(errors, 'multiplayer.contentVersion', 'must be a protocol-safe identifier');
  }
  if (!isPackRelativePath(multiplayer.adapter)) addError(errors, 'multiplayer.adapter', 'must be a pack-relative module path');
  if (!isStringArray(multiplayer.worldIdentity) || multiplayer.worldIdentity.length === 0) {
    addError(errors, 'multiplayer.worldIdentity', 'must be a non-empty string array');
  }
  if (!isNonEmptyString(multiplayer.instanceSupport)) {
    addError(errors, 'multiplayer.instanceSupport', 'must be a non-empty string');
  }
  if (!Array.isArray(multiplayer.avatars) || multiplayer.avatars.length === 0) {
    addError(errors, 'multiplayer.avatars', 'must be a non-empty array');
    return;
  }
  for (const [index, avatar] of multiplayer.avatars.entries()) {
    const path = `multiplayer.avatars[${index}]`;
    if (!isObject(avatar)) {
      addError(errors, path, 'must be an object');
      continue;
    }
    if (!isNonEmptyString(avatar.appearance)) addError(errors, `${path}.appearance`, 'must be a non-empty string');
    if (!isNonEmptyString(avatar.resource)) addError(errors, `${path}.resource`, 'must be a non-empty string');
    if (!Array.isArray(avatar.transparent) || avatar.transparent.length !== 3
      || avatar.transparent.some((channel) => !Number.isInteger(channel) || channel < 0 || channel > 255)) {
      addError(errors, `${path}.transparent`, 'must be [r, g, b] byte values');
    }
    if (avatar.cellWidth !== undefined && !isPositiveInteger(avatar.cellWidth)) {
      addError(errors, `${path}.cellWidth`, 'must be a positive integer');
    }
    if (avatar.cellHeight !== undefined && !isPositiveInteger(avatar.cellHeight)) {
      addError(errors, `${path}.cellHeight`, 'must be a positive integer');
    }
    if (avatar.frames !== undefined && !isPositiveInteger(avatar.frames)) {
      addError(errors, `${path}.frames`, 'must be a positive integer');
    }
  }
}

function validateCapabilities(capabilities, rendering, nuzlocke, errors) {
  if (!isObject(capabilities)) {
    addError(errors, 'capabilities', 'must be an object');
    return;
  }
  if (!Array.isArray(capabilities.rendering) || capabilities.rendering.length === 0) {
    addError(errors, 'capabilities.rendering', 'must be a non-empty array');
  } else {
    const modes = new Set(rendering?.modes ?? []);
    for (const mode of capabilities.rendering) {
      if (!RENDERING_MODES.includes(mode)) addError(errors, 'capabilities.rendering', `unknown mode ${mode}`);
      if (!modes.has(mode)) addError(errors, 'capabilities.rendering', `${mode} is not declared in rendering.modes`);
    }
  }
  if (!PRESENCE_LEVELS.includes(capabilities.presence)) {
    addError(errors, 'capabilities.presence', `must be one of ${PRESENCE_LEVELS.join(', ')}`);
  }
  if (!RULES_LEVELS.includes(capabilities.rules)) {
    addError(errors, 'capabilities.rules', `must be one of ${RULES_LEVELS.join(', ')}`);
  }
  if (!LINK_LEVELS.includes(capabilities.link)) {
    addError(errors, 'capabilities.link', `must be one of ${LINK_LEVELS.join(', ')}`);
  }
  if (typeof capabilities.customUi !== 'boolean') {
    addError(errors, 'capabilities.customUi', 'must be a boolean');
  }
  const rules = nuzlocke?.support ?? 'none';
  if (rules !== capabilities.rules) {
    addError(errors, 'capabilities.rules', `must match nuzlocke.support (${rules})`);
  }
}

function validateNuzlocke(nuzlocke, errors, resourceIds, run) {
  if (!isObject(nuzlocke)) {
    addError(errors, 'nuzlocke', 'must be an object');
    return;
  }
  if (!RULES_LEVELS.includes(nuzlocke.support)) {
    addError(errors, 'nuzlocke.support', `must be one of ${RULES_LEVELS.join(', ')}`);
    return;
  }
  if (nuzlocke.support === 'none') return;

  if (!isPackRelativePath(nuzlocke.adapter)) {
    addError(errors, 'nuzlocke.adapter', 'must be a pack-relative RulesAdapter module path');
  }
  if (!isNonEmptyString(nuzlocke.areas) || !resourceIds.has(nuzlocke.areas)) {
    addError(errors, 'nuzlocke.areas', 'must reference a declared encounter-area resource');
  }
  if (!isObject(nuzlocke.clauses)) {
    if (nuzlocke.clauses !== undefined) addError(errors, 'nuzlocke.clauses', 'must be an object when present');
  }
  const requiredHooks = ['encounter', 'captureGate', 'faintRelease', 'reviveGate'];
  if (!isStringArray(nuzlocke.requiredHooks) || nuzlocke.requiredHooks.length === 0) {
    addError(errors, 'nuzlocke.requiredHooks', 'must list the required RulesAdapter hook IDs');
  } else {
    for (const hook of nuzlocke.requiredHooks) {
      if (!requiredHooks.includes(hook)) addError(errors, 'nuzlocke.requiredHooks', `unknown required hook ${hook}`);
    }
    if (nuzlocke.support === 'enforce') {
      for (const hook of requiredHooks) {
        if (!nuzlocke.requiredHooks.includes(hook)) addError(errors, 'nuzlocke.requiredHooks', `enforced RulesAdapter must require ${hook}`);
      }
    }
  }
  if (nuzlocke.support === 'enforce'
      && (run?.support !== 'enforce' || !run.modes?.includes('nuzlocke'))) {
    addError(errors, 'nuzlocke.support', 'enforced Nuzlocke requires an enforced run adapter that declares nuzlocke mode');
  }
}

function validateRun(run, errors, resourceIds = new Set()) {
  if (!isObject(run)) {
    addError(errors, 'run', 'must be an object when present');
    return;
  }
  if (!isPackRelativePath(run.adapter)) addError(errors, 'run.adapter', 'must be a pack-relative module path');
  if (!['none', 'observe', 'enforce'].includes(run.support)) {
    addError(errors, 'run.support', 'must be none, observe or enforce');
  }
  if (!Array.isArray(run.modes) || !run.modes.every((mode) => ['nuzlocke', 'soullink'].includes(mode))) {
    addError(errors, 'run.modes', 'must be an array containing only nuzlocke or soullink');
  }
  if (!isObject(run.capabilities)) {
    addError(errors, 'run.capabilities', 'must be an object');
    return;
  }
  for (const capability of ['encounter', 'captureGate', 'faintRelease', 'reviveGate']) {
    if (!['none', 'observe', 'enforce'].includes(run.capabilities[capability])) {
      addError(errors, `run.capabilities.${capability}`, 'must be none, observe or enforce');
    }
  }
  if (!['none', 'enforce'].includes(run.capabilities.linkedPcBoxing)) {
    addError(errors, 'run.capabilities.linkedPcBoxing', 'must be none or enforce');
  }
  if (run.modes?.includes('soullink') && run.capabilities.linkedPcBoxing === undefined) {
    addError(errors, 'run.capabilities.linkedPcBoxing', 'must declare the SoulLink linked-PC boxing capability');
  }
  if (!['none', 'table', 'macro'].includes(run.capabilities.quickStart)) {
    addError(errors, 'run.capabilities.quickStart', 'must be none, table or macro');
  }
  if (!['none', 'map-data', 'map'].includes(run.capabilities.tracker)) {
    addError(errors, 'run.capabilities.tracker', 'must be none, map-data or map');
  }
  if (run.capabilities.tracker !== 'none' && !resourceIds.has(run.regionMapResource)) {
    addError(errors, 'run.regionMapResource', 'must reference a declared map data resource');
  }
  if (run.quickStartBaseResource !== undefined && !resourceIds.has(run.quickStartBaseResource)) {
    addError(errors, 'run.quickStartBaseResource', 'must reference a declared base-save resource');
  }
  if (!isObject(run.capabilities.randomizer)) {
    addError(errors, 'run.capabilities.randomizer', 'must be an object');
  } else {
    for (const feature of ['wild', 'trainers', 'gyms', 'starters']) {
      if (typeof run.capabilities.randomizer[feature] !== 'boolean') {
        addError(errors, `run.capabilities.randomizer.${feature}`, 'must be a boolean');
      }
    }
  }
  if (run.support === 'enforce' && run.modes?.includes('soullink')
      && (run.capabilities.encounter !== 'enforce' || run.capabilities.captureGate !== 'enforce')) {
    addError(errors, 'run.capabilities', 'enforced SoulLink requires enforced encounter and capture gates');
  }
}

function validateParty(party, errors) {
  if (!isObject(party)) {
    addError(errors, 'party', 'must be an object when present');
    return;
  }
  if (!isPackRelativePath(party.adapter)) addError(errors, 'party.adapter', 'must be a pack-relative module path');
}

export function validateManifest(value, {
  packId = '',
  requireDigests = true,
} = {}) {
  const errors = [];
  if (!isObject(value)) {
    return { ok: false, errors: [{ path: '', message: 'manifest must be an object' }], manifest: null };
  }

  if (value.schemaVersion !== MANIFEST_SCHEMA_VERSION) {
    addError(errors, 'schemaVersion', `must be ${MANIFEST_SCHEMA_VERSION}`);
  }
  for (const section of REQUIRED_SECTIONS) {
    if (!isObject(value[section]) && !Array.isArray(value[section])) {
      addError(errors, section, 'is required');
    }
  }

  if (!isObject(value.game)) {
    addError(errors, 'game', 'must be an object');
  } else {
    if (!PACK_ID_RE.test(value.game.id || '')) addError(errors, 'game.id', 'must match [a-z0-9-]{1,32}');
    if (packId && value.game.id !== packId) addError(errors, 'game.id', `must match pack directory "${packId}"`);
    if (!isNonEmptyString(value.game.title)) addError(errors, 'game.title', 'must be a non-empty string');
    if (!VERSION_RE.test(value.game.packVersion || '')) addError(errors, 'game.packVersion', 'must be a version identifier');
    if (value.game.revision !== undefined && typeof value.game.revision !== 'string') {
      addError(errors, 'game.revision', 'must be a string');
    }
  }

  if (!isObject(value.build)) {
    addError(errors, 'build', 'must be an object');
  } else {
    if (!isNonEmptyString(value.build.source)) addError(errors, 'build.source', 'must be a non-empty string');
    if (!VERSION_RE.test(value.build.sourceRevision || '')) addError(errors, 'build.sourceRevision', 'must be a pinned revision');
    if (!isNonEmptyString(value.build.recipe)) addError(errors, 'build.recipe', 'must be a non-empty string');
    if (!isNonEmptyString(value.build.artifact)) addError(errors, 'build.artifact', 'must be a non-empty string');
    if (value.build.toolchain !== undefined && typeof value.build.toolchain !== 'string') {
      addError(errors, 'build.toolchain', 'must be a string');
    }
  }

  validateRuntime(value.runtime, errors, { requireDigests });
  validateRendering(value.rendering, errors);

  if (!Array.isArray(value.resources)) {
    addError(errors, 'resources', 'must be an array');
  } else {
    const ids = new Set();
    for (const [index, resource] of value.resources.entries()) {
      validateResource(resource, `resources[${index}]`, errors, { requireDigests });
      if (isObject(resource) && isNonEmptyString(resource.id)) {
        if (ids.has(resource.id)) addError(errors, `resources[${index}].id`, 'must be unique');
        ids.add(resource.id);
      }
    }
  }

  validateSaves(value.saves, errors);

  const resourceIds = new Set((Array.isArray(value.resources) ? value.resources : [])
    .filter((resource) => isObject(resource) && isNonEmptyString(resource.id))
    .map((resource) => resource.id));
  if (value.run !== undefined) {
    validateRun(value.run, errors, resourceIds);
  }

  if (value.party !== undefined) validateParty(value.party, errors);

  const presence = value.capabilities?.presence;
  if (presence !== undefined && presence !== 'none') validateMultiplayer(value.multiplayer, errors);
  else if (value.multiplayer !== undefined && !isObject(value.multiplayer)) {
    addError(errors, 'multiplayer', 'must be an object when present');
  }

  validateNuzlocke(value.nuzlocke, errors, resourceIds, value.run);

  validateCapabilities(value.capabilities, value.rendering, value.nuzlocke, errors);

  if (value.interiorSupport !== undefined && !INTERIOR_SUPPORT_LEVELS.includes(value.interiorSupport)) {
    addError(errors, 'interiorSupport', `must be one of ${INTERIOR_SUPPORT_LEVELS.join(', ')}`);
  }

  if (value.verification !== undefined) {
    if (!isObject(value.verification) || !isStringArray(value.verification.evidence)) {
      addError(errors, 'verification.evidence', 'must be a string array');
    }
  }

  return { ok: errors.length === 0, errors, manifest: errors.length === 0 ? value : null };
}

export function validatePackIndex(value) {
  const errors = [];
  if (!isObject(value)) return { ok: false, errors: [{ path: '', message: 'index must be an object' }] };
  if (value.schemaVersion !== MANIFEST_SCHEMA_VERSION) {
    addError(errors, 'schemaVersion', `must be ${MANIFEST_SCHEMA_VERSION}`);
  }
  if (!isNonEmptyString(value.default)) addError(errors, 'default', 'must be a game id');
  if (!Array.isArray(value.games) || value.games.length === 0) {
    addError(errors, 'games', 'must be a non-empty array');
    return { ok: false, errors };
  }
  const ids = new Set();
  for (const [index, entry] of value.games.entries()) {
    const path = `games[${index}]`;
    if (!isObject(entry)) {
      addError(errors, path, 'must be an object');
      continue;
    }
    if (!PACK_ID_RE.test(entry.id || '')) addError(errors, `${path}.id`, 'must match [a-z0-9-]{1,32}');
    if (ids.has(entry.id)) addError(errors, `${path}.id`, 'must be unique');
    ids.add(entry.id);
    if (!isNonEmptyString(entry.title)) addError(errors, `${path}.title`, 'must be a non-empty string');
    if (!VERSION_RE.test(entry.packVersion || '')) addError(errors, `${path}.packVersion`, 'must be a version identifier');
    if (!isResourceUrl(entry.manifest)) addError(errors, `${path}.manifest`, 'must be a pack-relative or same-origin URL');
    if (entry.summary !== undefined && typeof entry.summary !== 'string') {
      addError(errors, `${path}.summary`, 'must be a string');
    }
    if (entry.hidden !== undefined && typeof entry.hidden !== 'boolean') {
      addError(errors, `${path}.hidden`, 'must be a boolean');
    }
    if (entry.cover !== undefined && !isResourceUrl(entry.cover)) {
      addError(errors, `${path}.cover`, 'must be a pack-relative or same-origin URL');
    }
  }
  if (!ids.has(value.default)) addError(errors, 'default', 'must reference an installed game');
  return { ok: errors.length === 0, errors };
}

export function formatValidationErrors(packId, errors) {
  return errors.map((error) => {
    const prefix = packId ? `pack ${packId}` : 'pack';
    return error.path ? `${prefix}: ${error.path} ${error.message}` : `${prefix}: ${error.message}`;
  }).join('\n');
}
