// Generate the browser move-name lookup from Emerald's C move constants and
// localized text table so move-learning UI stays aligned with the game data.

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const game = resolve(here, '..');
const constantsPath = join(game, 'include', 'constants', 'moves.h');
const namesPath = join(game, 'src', 'data', 'text', 'move_names.h');
const outputPath = join(game, 'web', 'packs', 'shared', 'move-names-emerald.mjs');

export function parseMoveIds(text) {
  const ids = new Map();
  for (const line of text.split(/\r?\n/)) {
    const match = line.match(/^\s*#define\s+(MOVE_[A-Z0-9_]+)\s+(\d+)\s*$/);
    if (match) ids.set(match[1], Number(match[2]));
  }
  return ids;
}

export function parseMoveNames(text) {
  const names = new Map();
  for (const line of text.split(/\r?\n/)) {
    const match = line.match(/^\s*\[(MOVE_[A-Z0-9_]+)\]\s*=\s*_\("((?:\\.|[^"\\])*)"\)\s*,?\s*$/);
    if (match) names.set(match[1], match[2].replace(/\\"/g, '"').replace(/\\\\/g, '\\'));
  }
  return names;
}

export function buildMoveNameTable(ids, names) {
  const table = {};
  for (const [constant, id] of ids) {
    const name = names.get(constant);
    if (name !== undefined) table[id] = name;
  }
  return table;
}

export function moveNameModuleSource(table) {
  const rows = Object.entries(table)
    .sort((left, right) => Number(left[0]) - Number(right[0]))
    .map(([id, name]) => `  ${id}: ${JSON.stringify(name)},`)
    .join('\n');
  return `// Generated by tools/generate_move_names.mjs. Do not edit by hand.\nexport const EMERALD_MOVE_NAMES = Object.freeze({\n${rows}\n});\n\nexport function moveName(id) {\n  return EMERALD_MOVE_NAMES[id] ?? null;\n}\n`;
}

export async function generateMoveNames({ constants = constantsPath, names = namesPath } = {}) {
  const [constantsText, namesText] = await Promise.all([
    readFile(constants, 'utf8'),
    readFile(names, 'utf8'),
  ]);
  const ids = parseMoveIds(constantsText);
  const localizedNames = parseMoveNames(namesText);
  const table = buildMoveNameTable(ids, localizedNames);
  const missing = [...ids.keys()].filter((key) => !localizedNames.has(key));
  if (missing.length) throw new Error(`move names are missing for ${missing.join(', ')}`);
  return table;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const table = await generateMoveNames();
  await writeFile(outputPath, moveNameModuleSource(table));
  console.log(`Generated ${Object.keys(table).length} move names -> ${outputPath}`);
}
