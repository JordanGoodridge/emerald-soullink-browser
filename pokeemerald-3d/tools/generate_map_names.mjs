// Generates web/presence/map-names.mjs from the map group constants.
//
// Presence sends only mapGroup/mapNum, so readable locations must be resolved
// locally. The table is generated rather than hand-maintained so it stays in
// step with the map list.
//
//   node pokeemerald-3d/tools/generate_map_names.mjs

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const game = resolve(here, '..');
const args = process.argv.slice(2);
const sourceArg = args.find((arg) => arg.startsWith('--source='));
const outputArg = args.find((arg) => arg.startsWith('--output='));
const source = sourceArg ? resolve(sourceArg.slice('--source='.length)) : join(game, 'include', 'constants', 'map_groups.h');
const target = outputArg ? resolve(outputArg.slice('--output='.length)) : join(game, 'web', 'presence', 'map-names.mjs');

function titleWord(word, index) {
  if (word === 'POKEMON') return 'Pokémon';
  if (word === 'PC') return 'PC';
  if (word === 'HP') return 'HP';
  if (word === 'TV') return 'TV';
  if (/^\d+[A-Z]?$/.test(word)) return word;
  if (/^[A-Z]\d+$/.test(word)) return word;
  const lower = word.toLowerCase();
  return lower.charAt(0).toUpperCase() + lower.slice(1);
}

export function prettifyMapName(constant) {
  const raw = constant.replace(/^MAP_/, '');
  const route = raw.match(/^ROUTE(\d+)$/);
  if (route) return `Route ${route[1]}`;
  return raw
    .split('_')
    .filter(Boolean)
    .map((word, index) => titleWord(word, index))
    .join(' ');
}

const text = await readFile(source, 'utf8');
const entries = [];
const pattern = /^\s*(MAP_[A-Z0-9_]+)\s*=\s*\((\d+)\s*\|\s*\((\d+)\s*<<\s*8\)\)/gm;
for (const match of text.matchAll(pattern)) {
  const [, constant, num, group] = match;
  entries.push([`${Number(group)}:${Number(num)}`, prettifyMapName(constant)]);
}

if (!entries.length) throw new Error(`no map constants found in ${source}`);
entries.sort((a, b) => a[0].localeCompare(b[0], undefined, { numeric: true }));

let output;
if (target.endsWith('.json')) {
  output = `${JSON.stringify(Object.fromEntries(entries), null, 2)}\n`;
} else {
  const lines = entries.map(([key, label]) => `  '${key}': ${JSON.stringify(label)},`).join('\n');
  output = `// Generated by tools/generate_map_names.mjs. Do not edit by hand.

export const MAP_NAMES = Object.freeze({
${lines}
});

export function mapNameFor(world) {
  if (!world) return null;
  return MAP_NAMES[\`\${world.mapGroup}:\${world.mapNum}\`] ?? null;
}
`;
}

await writeFile(target, output, 'utf8');
console.log(`Wrote ${entries.length} map names to ${target}`);
